"""Пакет для внешней нейросети.

Собирает ZIP, который можно целиком отдать любому чат-боту: данные, пояснение
к ним и готовый запрос. Нужен, когда своего ключа нет или хочется разобрать
проблему там, где удобнее.

Пояснение в пакете важнее самих данных: без него нейросеть видит набор чисел
и начинает советовать наугад. Поэтому в `КАК_РАЗБИРАТЬ.md` описано, что
означает каждый раздел, какие выводы из него следуют и чего делать не стоит.
"""

from __future__ import annotations

import json
import logging
import zipfile
from datetime import datetime
from pathlib import Path

from app.core import paths
from app.core.diagnostics import snapshot as snapshot_module

log = logging.getLogger(__name__)

SNAPSHOT_NAME = "состояние.json"
GUIDE_NAME = "КАК_РАЗБИРАТЬ.md"
PROMPT_NAME = "ЗАПРОС.txt"
LOG_NAME = "логи/app.log"

GUIDE = """\
# Что это за данные и как их разбирать

Это снимок состояния программы ZapretXmel — графической надстройки над
`zapret` (обход блокировок по DPI на Windows). Пользователь просит понять,
почему у него не работает доступ к какому-то сервису.

## Как устроен обход

`winws.exe` перехватывает пакеты через драйвер WinDivert и портит их так, чтобы
оборудование провайдера не опознало запрещённый сайт, а сервер — понял запрос.
Набор таких приёмов называется **стратегией**: это цепочка секций, у каждой свой
фильтр (порты, списки доменов) и свой способ обхода. Универсальной стратегии не
существует — у разных провайдеров работают разные, поэтому их подбирают перебором.

Запускаться обход может двумя способами: службой Windows (тогда он работает и без
программы, стартует вместе с системой) или обычным процессом (живёт, пока открыта
программа).

## Разделы снимка

- **обстановка** — версия Windows, права, активный VPN, доступные протоколы.
- **ядро** — установленная сборка zapret: версия, число стратегий, путь.
- **обход** — что работает прямо сейчас: служба, процессы `winws`, их командные строки.
- **настройки сборки** — режим ipset, игровой фильтр, пользовательские списки.
- **система** — то, что мешает обходу чаще всего.
- **находки** — выводы встроенных проверок, уже с важностью.
- **последний подбор** — результат последнего перебора стратегий по сервисам.
- **лог** — хвост журнала программы.

## На что смотреть в первую очередь

1. **Активный VPN.** Если в «обстановке» указан туннель, все измерения
   бессмысленны: они мерили VPN, а не провайдера. Это первое, что нужно сказать.
2. **Права администратора.** Без них служба и драйвер недоступны.
3. **Base Filtering Engine** — без этой службы Windows обход не работает вообще.
4. **Конфликтующие программы** — второй обходчик DPI, Adguard, Killer, Check Point.
5. **Служба работает, а процессов `winws` ноль** — обход падает при старте;
   смотрите лог и проверьте, не удалил ли антивирус файлы ядра.
6. **Результаты подбора.** Строка «без обхода» — точка отсчёта. Если без обхода
   уже всё хорошо, значит блокировки на этих целях нет, и победителя быть не может.

## Чего делать не стоит

- Не советовать «переустановить Windows», «сменить DNS на 8.8.8.8» и прочее
  наугад: в снимке достаточно данных, чтобы назвать причину или честно сказать,
  что её по этим данным не видно.
- Не предлагать VPN как решение: человек пользуется обходом именно затем,
  чтобы обойтись без него.
- Не выдумывать названия стратегий. Используйте только те, что есть в снимке.
- Голосовой трафик Discord идёт по UDP и снаружи не проверяется. Если все
  проверки проходят, а голос не работает — дело в UDP-секциях стратегии.

## Что хочется получить в ответ

1. Вердикт одной фразой: работает или нет, и что именно сломано.
2. Вероятная причина — со ссылкой на конкретные поля снимка.
3. Список действий по порядку, от самого вероятного к запасным.
4. Если причина по этим данным не определяется — так и скажите, и укажите,
   чего не хватает.
"""

PROMPT = """\
Ты разбираешь неполадку с обходом блокировок на Windows.

В архиве рядом лежит файл `{guide}` — прочитай его первым, там описано, как
устроен обход и как читать данные. Сами данные — в `{snapshot}`.

Проблема со слов пользователя:
{problem}

Что уже замечено автоматическими проверками:
{findings}

Ответь по-русски и по делу:
1. Вердикт одной фразой.
2. Вероятная причина со ссылкой на конкретные поля снимка.
3. Что сделать — по шагам, от самого вероятного к запасным.
4. Если данных не хватает, скажи прямо, чего именно.
"""


def _format_findings(problems: list[str]) -> str:
    if not problems:
        return "— автоматические проверки ничего подозрительного не нашли."
    return "\n".join(f"- {item}" for item in problems)


def build_prompt(snapshot: dict, problem: str = "") -> str:
    """Готовый запрос, который можно вставить в любой чат."""
    return PROMPT.format(
        guide=GUIDE_NAME,
        snapshot=SNAPSHOT_NAME,
        problem=problem.strip() or "— не описана, разберись по данным.",
        findings=_format_findings(snapshot_module.problems_only(snapshot)),
    )


def export(
    problem: str = "",
    sanitized: bool = True,
    destination: Path | None = None,
) -> Path:
    """Собирает ZIP с данными, пояснением и запросом."""
    data = snapshot_module.build(sanitized=sanitized)

    directory = destination or (paths.data_dir() / "bundles")
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"zapretxmel-диагностика-{datetime.now():%Y%m%d-%H%M%S}.zip"

    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr(
            SNAPSHOT_NAME, json.dumps(data, indent=2, ensure_ascii=False)
        )
        archive.writestr(GUIDE_NAME, GUIDE)
        archive.writestr(PROMPT_NAME, build_prompt(data, problem))

        log_path = paths.logs_dir() / "app.log"
        if log_path.exists():
            archive.write(log_path, LOG_NAME)

        for report in sorted(paths.history_dir().glob("autopick-*.json"), reverse=True)[:3]:
            archive.write(report, f"подборы/{report.name}")

    log.info("Диагностический пакет собран: %s", path.name)
    return path
