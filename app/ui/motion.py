"""Выключатель анимаций — один на всё приложение.

Анимации здесь короткие и служебные: они подсказывают, что состояние
сменилось, а не развлекают. Но на слабой машине, через удалённый рабочий
стол или просто на вкус любая анимация лишняя, поэтому её можно выключить.

Длительность спрашивается в момент запуска анимации, а не при создании
виджета: галочка в настройках должна срабатывать сразу, а не после
перезапуска программы.
"""

from __future__ import annotations

_enabled = True


def set_enabled(value: bool) -> None:
    global _enabled
    _enabled = bool(value)


def enabled() -> bool:
    return _enabled


def duration(ms: int) -> int:
    """Сколько должна длиться анимация прямо сейчас.

    С выключенными анимациями возвращается ноль: Qt доводит значение до
    конечного за один кадр, и ветвить код в каждом виджете не нужно.
    """
    return ms if _enabled else 0
